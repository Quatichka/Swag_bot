"""SWAG Script — тонкий связный рукописный шрифт по мотивам подписи «swag studio» из логотипа.

Как в образце: очень низкие строчные, длинные наклонные стойки и выносные,
буквы соединяются длинными тонкими линиями. Каждая строчная начинается в точке (0, J)
и заканчивается в (ширина, J) — поэтому соседние буквы стыкуются в одну линию.

Каждая буква описана как набор штрихов (точек, через которые проходит перо);
штрихи сглаживаются кривой Катмулла–Рома и обводятся монолинейным пером.
Строчные латиница + кириллица (прописные показываются строчными), цифры, знаки.
Запуск: python fonts/build_script.py  ->  fonts/SwagScript.ttf
"""
