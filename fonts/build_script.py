def hump(x0, x1, end_tail=True):
    """Арка «n»: от стойки x0 вверх и вниз к x1."""
    mid = (x0 + x1) / 2
    pts = [(x0, X * 0.55), (mid - 15, X * 0.97), (x1 - 8, X * 0.75), (x1, X * 0.3)]
    return pts + (ex(x1)[0:1] + [(x1 + 40, 0), (x1 + 80, 35)] if end_tail else [(x1, 0)])


def cup(x0, x1):
    """Чаша «u»: сверху x0 вниз и вверх к x1."""
    mid = (x0 + x1) / 2
    return [(x0, X), (x0 + 3, X * 0.35), (mid - 20, 0), (x1 - 10, X * 0.3), (x1, X)]


def stem(x, top=X, bottom=0, tail=True):
    pts = [(x, top), (x - 3, (top + bottom) / 2), (x, bottom + 40 if tail else bottom)]
    return pts + ([(x + 35, bottom), (x + 80, bottom + 35)] if tail else [])


