# ---------------------------------------------------------------- сборка

def drawer(strokes):
    def draw(pen):
        for stroke in strokes:
            pts = [skew((p[0] * STRETCH, p[1]), SLANT) for p in stroke]
            line = catmull_rom(pts) if len(pts) > 2 else pts
            contour = simplify(stroke_outline(line, PEN), 0.6)
            pen.moveTo(_r(contour[0]))
            for p in contour[1:]:
                pen.lineTo(_r(p))
            pen.closePath()
    return draw


def _r(p):
    return round(p[0] + SB), round(p[1])


def advance(strokes) -> int:
    # ширина по строчной зоне: наклонённые верхушки выносных могут заходить на соседа, как в почерке
    xs = [skew((p[0] * STRETCH, min(max(p[1], 0), X)), SLANT)[0] for s in strokes for p in s]
    return int(max(xs) + PEN + SB * 2 - SLANT * X * 0.5)


def main() -> None:
    glyphs = {".notdef": (300, None), "space": (260, None)}
    cmap = {ord(" "): "space", 0xA0: "space"}

    def add(name, strokes, chars):
        glyphs[name] = (advance(strokes), drawer(strokes))
        for ch in chars:
            cmap[ord(ch)] = name

    for ch, strokes in S.items():
        add(ch, strokes, ch + ch.upper())
    for ch, strokes in C.items():
        add(f"uni{ord(ch):04X}", strokes, ch + ch.upper())
    for i, (name, strokes) in enumerate(DIGITS.items()):
        add(name, strokes, str(i))
    for name, (strokes, chars) in MARKS.items():
        add(name, strokes, chars)

    build_font(OUT, "SWAG Script", "Regular", glyphs, cmap, ascent=900, descent=-400)
    print("saved", OUT, len(glyphs), "glyphs")


if __name__ == "__main__":
    main()
