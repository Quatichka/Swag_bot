def entry(x_top=35):
    """Подход от соединительной линии к верху буквы."""
    return [(0, J), (x_top * 0.7, X * 0.8), (x_top, X)]


def bowl(x0=0):
    """Овал «a/d/g/q/д» с подходом слева: заходит в верх овала и обходит его против часовой."""
    return [(x0, J), (x0 + 70, 165), (x0 + 150, 212), (x0 + 100, X + 2), (x0 + 45, 175), (x0 + 38, 75),
            (x0 + 80, 5), (x0 + 140, 35), (x0 + 168, 130), (x0 + 175, X)]


def tail(x, end):
    """Короткая стойка вниз с выходом на соединительную линию в точке (end, J)."""
    return [(x, X), (x - 12, 70), (x - 6, 5), (x + 32, 8), (x + (end - x) * 0.7, 60), (end, J)]


def loop_down(x, end):
    """Выносная петля как у «g» из образца: вниз-влево, петля и длинный росчерк вправо-вверх."""
    return [(x, X), (x - 10, 0), (x - 35, -200), (x - 80, -315), (x - 125, -330), (x - 132, -270),
            (x - 70, -150), (x + 45, -20), (end, J)]


def stem_up(x_top=100):
    """Подъём от соединительной линии к верху высокой стойки (b, h, k)."""
    return [(0, J), (x_top * 0.5, 330), (x_top * 0.9, 600), (x_top, ASC - 10)]


def stem_down(x_top=100, x_bottom=40):
    return [(x_top, ASC - 10), (x_top * 0.6 + x_bottom * 0.4, 380), (x_bottom, 0)]


def dot(x, y=X + 110):
    return [(x, y)]


