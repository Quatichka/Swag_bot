# ---------------------------------------------------------------- сборка

def slant(p):
    x, y = p[0] * STRETCH, p[1]
    if y > X:
        y = X + (y - X) * ASC_K
    elif y < 0:
        y *= DSC_K
    extra = max(y - X, 0) + min(y, 0)  # только выше строчных и ниже строки
    return (x + y * SLANT + extra * SLANT_EXTRA) * SCALE, y * SCALE


def with_lead(strokes, chars_connect: bool):
    """Сдвигает букву вправо: подход к ней становится длинной диагональю от стыка, как в образце."""
    if not chars_connect:
        return strokes
    dx = LEAD / STRETCH
    out = [[(x + dx, y) for x, y in s] for s in strokes]
    first = out[0]
    if abs(first[0][0] - dx) < 1 and abs(first[0][1] - J) < 1:
        out[0] = [(0, J)] + first[1:]      # подход тянется от стыка прямо к верху буквы
    else:
        out.insert(0, [(0, J), (dx * 0.6, J + 25), first[0]])
    return out


def drawer(strokes):
    def draw(pen):
        for stroke in strokes:
            pts = [slant(p) for p in stroke]
            line = catmull_rom(pts) if len(pts) > 2 else pts
            contour = simplify(stroke_outline(line, PEN), 0.5)
            pen.moveTo(_r(contour[0]))
            for p in contour[1:]:
                pen.lineTo(_r(p))
            pen.closePath()
    return draw


def _r(p):
    return round(p[0]), round(p[1])


def advance(name: str, strokes) -> int:
    """Ширина = конец соединительной линии (x последней точки на высоте J), иначе по правому краю."""
    if name in ADV:
        return int(ADV[name] * STRETCH)
    ends = [s[-1] for s in strokes if abs(s[-1][1] - J) < 1]
    if ends:
        return int(max(x for x, _ in ends) * STRETCH)
    body = [x for s in strokes for x, y in s if y <= X + 20] or [x for s in strokes for x, _ in s]
    return int((max(body) + 60) * STRETCH)


def main() -> None:
    glyphs = {".notdef": (300, None), "space": (300, None)}
    cmap = {ord(" "): "space", 0xA0: "space"}

    def add(name, key, strokes, chars, connect=False):
        adv = int((advance(key, strokes) + (LEAD if connect else 0)) * SCALE)
        glyphs[name] = (adv, drawer(with_lead(strokes, connect)))
        for ch in chars:
            cmap[ord(ch)] = name

    for ch, strokes in S.items():
        add(ch, ch, strokes, ch + ch.upper(), connect=True)
    for ch, strokes in C.items():
        add(f"uni{ord(ch):04X}", ch, strokes, ch + ch.upper(), connect=True)
    for i, (name, strokes) in enumerate(DIGITS.items()):
        add(name, name, strokes, str(i))
    for name, (strokes, chars) in MARKS.items():
        add(name, name, strokes, chars)

    build_font(OUT, "SWAG Script", "Regular", glyphs, cmap, ascent=900, descent=-400)
    print("saved", OUT, len(glyphs), "glyphs")


if __name__ == "__main__":
    main()
